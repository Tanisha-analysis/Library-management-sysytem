-- ---------- 1. TABLES ----------
CREATE TABLE books (
  book_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title            VARCHAR2(150) NOT NULL,
  author           VARCHAR2(100) NOT NULL,
  category         VARCHAR2(50),
  total_copies     NUMBER(3) DEFAULT 1 NOT NULL CHECK (total_copies >= 0),
  available_copies NUMBER(3) DEFAULT 1 NOT NULL CHECK (available_copies >= 0)
);

CREATE TABLE members (
  member_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  VARCHAR2(100) NOT NULL,
  email      VARCHAR2(100) UNIQUE,
  phone      VARCHAR2(15),
  joined_on  DATE DEFAULT SYSDATE
);

CREATE TABLE issues (
  issue_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id     NUMBER NOT NULL REFERENCES books(book_id),
  member_id   NUMBER NOT NULL REFERENCES members(member_id),
  issue_date  DATE DEFAULT SYSDATE NOT NULL,
  due_date    DATE NOT NULL,
  return_date DATE,
  fine_amount NUMBER(8,2) DEFAULT 0
);

CREATE TABLE issue_audit (
  audit_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id   NUMBER,
  action     VARCHAR2(20),
  action_on  TIMESTAMP DEFAULT SYSTIMESTAMP,
  done_by    VARCHAR2(100)
);

