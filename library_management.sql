-- ---------- 3. TRIGGERS ----------
-- Auto-set due date (14 days) if not given
CREATE OR REPLACE TRIGGER trg_issues_due_date
BEFORE INSERT ON issues
FOR EACH ROW
BEGIN
  IF :NEW.due_date IS NULL THEN
    :NEW.due_date := NVL(:NEW.issue_date, SYSDATE) + 14;
  END IF;
END;
/

-- Audit every issue / return
CREATE OR REPLACE TRIGGER trg_issues_audit
AFTER INSERT OR UPDATE ON issues
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO issue_audit (issue_id, action, done_by)
    VALUES (:NEW.issue_id, 'ISSUED', USER);
  ELSIF UPDATING AND :OLD.return_date IS NULL AND :NEW.return_date IS NOT NULL THEN
    INSERT INTO issue_audit (issue_id, action, done_by)
    VALUES (:NEW.issue_id, 'RETURNED', USER);
  END IF;
END;
/

-- ---------- 4. FUNCTION : fine calculation (Rs 5 per late day) ----------
CREATE OR REPLACE FUNCTION calc_fine (p_issue_id IN NUMBER)
RETURN NUMBER
IS
  v_due     issues.due_date%TYPE;
  v_return  issues.return_date%TYPE;
  v_days    NUMBER;
  c_rate    CONSTANT NUMBER := 5;
BEGIN
  SELECT due_date, return_date
    INTO v_due, v_return
    FROM issues
   WHERE issue_id = p_issue_id;

  v_days := TRUNC(NVL(v_return, SYSDATE)) - TRUNC(v_due);
  RETURN GREATEST(v_days, 0) * c_rate;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN 0;
END calc_fine;
/

-- ---------- 5. PROCEDURE : issue a book ----------
CREATE OR REPLACE PROCEDURE issue_book (
  p_book_id   IN NUMBER,
  p_member_id IN NUMBER
)
IS
  v_avail    books.available_copies%TYPE;
  v_active   NUMBER;
  v_member   NUMBER;
  e_no_copy  EXCEPTION;
  e_limit    EXCEPTION;
  e_no_mem   EXCEPTION;
BEGIN
  SELECT COUNT(*) INTO v_member FROM members WHERE member_id = p_member_id;
  IF v_member = 0 THEN
    RAISE e_no_mem;
  END IF;

  SELECT available_copies INTO v_avail
    FROM books WHERE book_id = p_book_id FOR UPDATE;

  SELECT COUNT(*) INTO v_active
    FROM issues
   WHERE member_id = p_member_id AND return_date IS NULL;

  IF v_avail <= 0 THEN
    RAISE e_no_copy;
  ELSIF v_active >= 3 THEN
    RAISE e_limit;
  END IF;

  INSERT INTO issues (book_id, member_id, issue_date, due_date)
  VALUES (p_book_id, p_member_id, SYSDATE, SYSDATE + 14);

  UPDATE books
     SET available_copies = available_copies - 1
   WHERE book_id = p_book_id;

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20001, 'Book not found.');
  WHEN e_no_mem THEN
    RAISE_APPLICATION_ERROR(-20004, 'Member not found.');
  WHEN e_no_copy THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20002, 'No copies available for this book.');
  WHEN e_limit THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20003, 'Member already has 3 books issued.');
END issue_book;
/

-- ---------- 6. PROCEDURE : return a book ----------
CREATE OR REPLACE PROCEDURE return_book (p_issue_id IN NUMBER)
IS
  v_book_id  issues.book_id%TYPE;
  v_returned issues.return_date%TYPE;
  v_fine     NUMBER;
BEGIN
  SELECT book_id, return_date
    INTO v_book_id, v_returned
    FROM issues
   WHERE issue_id = p_issue_id FOR UPDATE;

  IF v_returned IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20005, 'This book is already returned.');
  END IF;

  UPDATE issues SET return_date = SYSDATE WHERE issue_id = p_issue_id;

  v_fine := calc_fine(p_issue_id);
  UPDATE issues SET fine_amount = v_fine WHERE issue_id = p_issue_id;

  UPDATE books
     SET available_copies = available_copies + 1
   WHERE book_id = v_book_id;

  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Book returned. Fine: Rs ' || v_fine);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20006, 'Issue record not found.');
END return_book;
/

-- ---------- 7. PROCEDURE : overdue report using CURSOR ----------
CREATE OR REPLACE PROCEDURE overdue_report
IS
  CURSOR c_overdue IS
    SELECT i.issue_id, m.full_name, b.title, i.due_date
      FROM issues i
      JOIN members m ON m.member_id = i.member_id
      JOIN books   b ON b.book_id   = i.book_id
     WHERE i.return_date IS NULL
       AND i.due_date < SYSDATE
     ORDER BY i.due_date;
  v_count NUMBER := 0;
BEGIN
  FOR r IN c_overdue LOOP
    v_count := v_count + 1;
    DBMS_OUTPUT.PUT_LINE(
      'Issue#' || r.issue_id || ' | ' || r.full_name || ' | ' || r.title ||
      ' | Due: ' || TO_CHAR(r.due_date, 'DD-MON-YYYY') ||
      ' | Fine so far: Rs ' || calc_fine(r.issue_id));
  END LOOP;

  IF v_count = 0 THEN
    DBMS_OUTPUT.PUT_LINE('No overdue books.');
  END IF;
END overdue_report;
/

-- ---------- 8. VIEW (use this for APEX reports) ----------
CREATE OR REPLACE VIEW v_issue_details AS
SELECT i.issue_id,
       b.title,
       m.full_name AS member_name,
       i.issue_date,
       i.due_date,
       i.return_date,
       CASE
         WHEN i.return_date IS NOT NULL THEN 'Returned'
         WHEN i.due_date < SYSDATE      THEN 'Overdue'
         ELSE 'Issued'
       END AS status,
       CASE WHEN i.return_date IS NULL THEN calc_fine(i.issue_id)
            ELSE i.fine_amount END AS fine
  FROM issues i
  JOIN books   b ON b.book_id   = i.book_id
  JOIN members m ON m.member_id = i.member_id;

